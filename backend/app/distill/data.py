"""Training data for reranker distillation (ADR 0015).

For each training question we keep the 30 candidate clauses that hybrid search finds
(exactly what the reranker sees in production) and the teacher reranker's score for
each. The student is then trained to reproduce the teacher's ranking of those 30.

Questions are generated by an LLM from clauses that are NOT in the evaluation set: a
clause used for evaluation never appears in training, or the evaluation would measure
memory instead of skill.
"""

import json
import logging
import random
import uuid
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from app.eval.dataset import GoldItem
from app.eval.generate import (
    SYSTEM_PROMPT,
    GeneratedQuestions,
    copies_clause,
    sample_clauses,
)
from app.llm.gateway import LLMGateway, complete_json
from app.llm.types import LLMRequest, Message
from app.retrieval.hybrid import HybridRetriever
from app.retrieval.rerank import Reranker

log = logging.getLogger(__name__)

CANDIDATES = 30  # the production reranker sees the top 30 fused candidates


@dataclass
class TrainQuery:
    group: str  # the source clause: its 3 language versions share a group
    language: str
    query: str
    source_key: str
    para_refs: list[str]


@dataclass
class TrainExample:
    group: str
    language: str
    query: str
    passages: list[str]
    teacher: list[float] = field(default_factory=list)  # teacher logits, one per passage


def held_out(items: list[GoldItem]) -> set[tuple[str, str]]:
    """(document, paragraph) pairs used by the evaluation set: never trained on."""
    return {(i.doc_source_key, ref) for i in items for ref in i.para_refs}


async def generate_queries(
    session_factory: async_sessionmaker[AsyncSession],
    gateway: LLMGateway,
    exclude: set[tuple[str, str]],
    *,
    n: int,
    per_document: int,
    seed: int,
) -> list[TrainQuery]:
    """English, Hinglish and Hindi questions for n clauses outside the evaluation set."""
    clauses = await sample_clauses(session_factory, n=10_000, per_document=per_document, seed=seed)
    clauses = [c for c in clauses if not any((c.source_key, r) in exclude for r in c.para_refs)][:n]
    out: list[TrainQuery] = []
    for i, clause in enumerate(clauses, start=1):
        request = LLMRequest(
            [
                Message("system", SYSTEM_PROMPT),
                Message("user", f"Clause ({clause.context.splitlines()[0]}):\n\n{clause.text}"),
            ],
            temperature=0.3,
            max_tokens=1500,
        )
        try:
            q = await complete_json(gateway, request, GeneratedQuestions.model_validate_json)
        except Exception as e:  # one bad clause must not stop the run
            log.warning("question generation failed for %s: %s", clause.para_refs, e)
            continue
        if not q.usable or not q.question_en.strip() or copies_clause(q.question_en, clause.text):
            continue
        group = uuid.uuid4().hex[:8]
        for language, text in (
            ("en", q.question_en),
            ("hinglish", q.question_hinglish),
            ("hi", q.question_hi),
        ):
            if text.strip():
                out.append(
                    TrainQuery(group, language, text.strip(), clause.source_key, clause.para_refs)
                )
        if i % 25 == 0:
            log.info("generated questions for %d/%d clauses", i, len(clauses))
    return out


async def score_with_teacher(
    queries: list[TrainQuery], retriever: HybridRetriever, teacher: Reranker
) -> list[TrainExample]:
    """`retriever` must have no reranker: we want the raw candidates, scored by the teacher."""
    examples: list[TrainExample] = []
    for i, q in enumerate(queries, start=1):
        hits, _ = await retriever.search(q.query, k=CANDIDATES)
        passages = [f"{h.context}\n{h.text}" for h in hits]  # same input as production
        if len(passages) < 2:
            continue
        examples.append(
            TrainExample(q.group, q.language, q.query, passages, teacher.score(q.query, passages))
        )
        if i % 100 == 0:
            log.info("teacher scored %d/%d questions", i, len(queries))
    return examples


def save(path: Path, rows: list[Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "".join(json.dumps(asdict(r), ensure_ascii=False) + "\n" for r in rows), encoding="utf-8"
    )


def load_queries(path: Path) -> list[TrainQuery]:
    return [TrainQuery(**json.loads(x)) for x in path.read_text(encoding="utf-8").splitlines() if x]


def load_examples(path: Path) -> list[TrainExample]:
    return [
        TrainExample(**json.loads(x)) for x in path.read_text(encoding="utf-8").splitlines() if x
    ]


def split_by_group(
    examples: list[TrainExample], dev_fraction: float, seed: int
) -> tuple[list[TrainExample], list[TrainExample]]:
    """Train/dev split by source clause, so the three language versions of one question
    never end up on both sides (that would leak the answer into the dev score)."""
    groups = sorted({e.group for e in examples})
    random.Random(seed).shuffle(groups)  # noqa: S311 - reproducible split, not security
    dev_groups = set(groups[: max(1, round(len(groups) * dev_fraction))])
    train = [e for e in examples if e.group not in dev_groups]
    dev = [e for e in examples if e.group in dev_groups]
    return train, dev
